create table
    measure (
        id bigint generated by default as identity,
        device varchar(255) not null,
        pressure float (53),
        temperature float (53),
        timestamp timestamp(6),
        primary key (id)
    )
with
    (
        tsdb.hypertable,
        tsdb.segmentby = 'device',
        tsdb.orderby = 'time DESC'
    );